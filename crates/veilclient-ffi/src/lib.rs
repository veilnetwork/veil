/// Connect to an veil daemon's IPC socket and perform the APP_HELLO
/// handshake. Returns an opaque [`VeilHandle`] on success, NULL on
/// failure (with `*err_out` set).
///
/// `socket_path` is treated as an anchor — see
/// [`veilclient::VeilClient::connect`] for backend discovery rules.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_connect(
    socket_path: *const u8,
    socket_path_len: usize,
    err_out: *mut *mut c_char,
) -> *mut VeilHandle {
    if unsafe { guard::ffi_prelude(err_out, "veil_connect") }.is_err() {
        return ptr::null_mut();
    }
    // Explicit-length text ABI: `(ptr, len)` UTF-8, validated by `slice_to_str`
    // (None on NULL, over-cap, or invalid UTF-8) — no NUL terminator required.
    let Some(path) = (unsafe { slice_to_str(socket_path, socket_path_len) }) else {
        unsafe {
            write_err(err_out, "socket_path is NULL or not valid UTF-8");
        }
        return ptr::null_mut();
    };
    let runtime = match build_handle_runtime() {
        Ok(rt) => rt,
        Err(e) => {
            unsafe {
                write_err(err_out, format!("failed to create tokio runtime: {e}"));
            }
            return ptr::null_mut();
        }
    };
    let client_res = runtime.block_on(async { VeilClient::connect(path).await });
    let client = match client_res {
        Ok(c) => c,
        Err(e) => {
            unsafe {
                write_err(err_out, format!("connect failed: {e}"));
            }
            return ptr::null_mut();
        }
    };
    let bundle = Arc::new(RuntimeBundle {
        runtime: std::mem::ManuallyDrop::new(runtime),
        client: TokioMutex::new(client),
        pending_mailbox_fetch: StdMutex::new(None),
        #[cfg(feature = "node-embedded")]
        cached_node_id: StdMutex::new(None),
    });
    // IPC keepalive. The daemon reaps an established IPC connection after
    // IPC_SESSION_IDLE_TIMEOUT (15 min) of BIDIRECTIONAL silence (audit U3
    // slow-loris defence), and this client has no transparent reconnect — a
    // quiet FFI connection (the dedicated media client between calls) was
    // silently dropped, after which every media operation failed with
    // "connection closed" until process restart. On the stand that surfaced
    // as a call with media dead in BOTH directions ~15 min after the
    // previous one. Tick a cheap inline query at a third of the timeout so
    // a live handle never ages out; errors are ignored (a genuinely dead
    // connection surfaces at the next real call site). The task holds only
    // a Weak — it must not keep the bundle (and thus the runtime) alive
    // after the host releases the handle; it exits when the upgrade fails
    // and dies with the runtime either way.
    {
        let weak = Arc::downgrade(&bundle);
        bundle.runtime.spawn(async move {
            const KEEPALIVE_TICK: std::time::Duration = std::time::Duration::from_secs(300);
            loop {
                tokio::time::sleep(KEEPALIVE_TICK).await;
                let Some(bundle) = weak.upgrade() else {
                    break;
                };
                let _ = tokio::time::timeout(std::time::Duration::from_secs(5), async {
                    let client = bundle.client.lock().await;
                    let _ = client.node_identity().await;
                })
                .await;
            }
        });
    }
    HandleTable::insert(
        handle_table(),
        VeilHandle {
            bundle,
            event_task: StdMutex::new(None),
            event_cb: Arc::new(StdMutex::new(None)),
            #[cfg(feature = "node-embedded")]
            anon_hub: TokioMutex::new(None),
        },
    ) as *mut VeilHandle
}

/// Release the handle. Outstanding apps / streams keep the runtime
/// alive via their own `Arc`; the runtime is dropped only when the last
/// reference goes away. Safe to call on NULL.
///
/// Defends against double-free. A NULL / already-freed / garbage / wrong-type
/// token is absent from the generational handle table → safe no-op; the
/// (opaque, non-pointer) token is never dereferenced (see [`HandleTable`]).
///
/// # Callback quiescence (audit V-01)
///
/// On return from a non-reentrant call this function guarantees that the
/// event trampoline will NEVER be entered again, so the host is free to
/// deallocate it immediately. Two steps, in this order, are what buy that:
///
/// 1. **Retire the callback slot.** An event the task has already dequeued but
///    not yet dispatched reads `None` and drops the event — no call, and no
///    orphaned callee-owned payload buffer.
/// 2. **Abort, then JOIN.** `abort()` alone is a *request*: the recv/event
///    loops run whole dispatch sections (slot copy → buffer alloc → C call)
///    with no `.await` in them, so a cancellation landing inside such a
///    section takes effect only at the NEXT await point — after the callback
///    has already run. Awaiting the aborted `JoinHandle` resolves exactly when
///    the task has actually stopped, which is the only observation that closes
///    the window. The two `await Future.delayed(Duration.zero)` yields the
///    Dart wrapper used to paper over this are removed accordingly.
///
/// The join is skipped when called from inside a Tokio runtime — joining a
/// task of the very runtime driving the caller would deadlock. That path
/// defers abort+join+drop onto the runtime instead; step 1 has already run
/// synchronously, so no NEW dispatch can start, but a dispatch already past
/// the slot copy may still complete after this returns. No supported host
/// takes that path (Dart runs FFI on its isolate thread, never a tokio
/// worker); it exists so a misuse degrades instead of deadlocking.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_close(handle: *mut VeilHandle) {
    if handle.is_null() {
        return;
    }
    // Claim the live entry from the generational table. A double-close /
    // already-freed / garbage / wrong-type token is absent → safe no-op, and
    // the (opaque) token is never dereferenced as a pointer.
    let Some(h) = HandleTable::remove(handle_table(), handle as usize) else {
        return;
    };
    // Steps 1 + 2a — retire the callback slot, then abort the task.
    let task = retire_dispatch_callback(&h.event_cb, &h.event_task);
    // Step 2b — wait for the task to actually be gone. Nothing the join needs
    // lives in `h` (the runtime is `ManuallyDrop` and outlives every handle),
    // so the entry itself can go now on either path.
    let bundle = Arc::clone(&h.bundle);
    drop(h);
    await_retired_task(&bundle.runtime, task, std::future::ready(()));
}

