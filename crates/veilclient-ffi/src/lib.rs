#[cfg(feature = "node-embedded")]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_revoke_identity_device_zeroize(
    credential: *const u8,
    credential_len: usize,
    secret: *mut u8,
    secret_len: usize,
    veil_dir: *const u8,
    veil_dir_len: usize,
    device_id: *const u8,
    changed_out: *mut u8,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe {
        clear_err(err_out);
    }
    let Some(_guard) = (unsafe { ZeroOnDrop::arm(secret, secret_len) }) else {
        unsafe { write_err(err_out, "secret is NULL or too long (>4 KiB)") };
        return VEIL_ERR_INVALID_ARG;
    };

    // AFTER the guard: a NULL ancillary argument used to return the documented
    // error with the caller's secret still sitting in their memory (report14
    // V14-M14). The secret's own pointer and length are `arm`'s business
    // above; this is only about the rest.
    if device_id.is_null() {
        unsafe {
            write_err(err_out, "device_id is NULL");
        }
        return VEIL_ERR_INVALID_ARG;
    }
    let Some(dir_str) = (unsafe { slice_to_str(veil_dir, veil_dir_len) }) else {
        unsafe {
            write_err(err_out, "veil_dir is NULL or invalid UTF-8");
        }
        return VEIL_ERR_INVALID_ARG;
    };
    let secret_bytes = unsafe { std::slice::from_raw_parts(secret as *const u8, secret_len) };
    let master = match unsafe {
        master_secret_for_device_lifecycle(credential, credential_len, secret_bytes, err_out)
    } {
        Ok(m) => m,
        Err(code) => return code,
    };

    let mut id = [0u8; 32];
    id.copy_from_slice(unsafe { std::slice::from_raw_parts(device_id, 32) });

    let now_unix = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    match veil_identity::sovereign_flow::revoke_identity_device(
        std::path::Path::new(dir_str),
        master,
        &id,
        now_unix,
    ) {
        Ok(changed) => {
            if !changed_out.is_null() {
                unsafe { *changed_out = u8::from(changed) };
            }
            VEIL_OK
        }
        Err(e) => {
            unsafe {
                write_err(err_out, format!("revoke_identity_device: {e}"));
            }
            VEIL_ERR
        }
    }
}

/// The master Ed25519 secret out of a node config, or the `VEIL_ERR_*` to
/// return. Shared by the two config-taking identity entry points so they
/// cannot drift on what counts as a usable config.
#[cfg(feature = "node-embedded")]
fn master_signing_key_from_config(
    toml: &str,
    err_out: *mut *mut c_char,
) -> Result<zeroize::Zeroizing<[u8; 32]>, c_int> {
    let config = match veil_cfg::parse_toml_str(toml) {
        Ok(c) => c,
        Err(e) => {
            unsafe {
                write_err(err_out, format!("config parse failed: {e}"));
            }
            return Err(VEIL_ERR_INVALID_ARG);
        }
    };
    let Some(identity) = config.identity else {
        unsafe {
            write_err(err_out, "config carries no [identity]");
        }
        return Err(VEIL_ERR_INVALID_ARG);
    };
    if identity.algo != veil_types::SignatureAlgorithm::Ed25519 {
        unsafe {
            write_err(err_out, "delegation requires an Ed25519 identity");
        }
        return Err(VEIL_ERR_INVALID_ARG);
    }
    let decoded: zeroize::Zeroizing<Vec<u8>> = {
        use base64::Engine as _;
        match base64::engine::general_purpose::STANDARD.decode(identity.private_key.as_str()) {
            Ok(v) => zeroize::Zeroizing::new(v),
            Err(e) => {
                unsafe {
                    write_err(err_out, format!("private_key decode failed: {e}"));
                }
                return Err(VEIL_ERR_INVALID_ARG);
            }
        }
    };
    if decoded.len() != 32 {
        unsafe {
            write_err(
                err_out,
                format!("private_key must be 32 bytes, got {}", decoded.len()),
            );
        }
        return Err(VEIL_ERR_INVALID_ARG);
    }
    let mut out = zeroize::Zeroizing::new([0u8; 32]);
    out.copy_from_slice(&decoded);
    Ok(out)
}

/// Derive the master signing key from a BIP-39 phrase, writing 32 bytes to
/// `out_master_sk`. No mining, no disk, no config.
///
/// An application that gives each device a transport key of its own can no
/// longer treat its node config as the master — the config becomes a device
/// key — but it still needs the master to admit further devices, at a moment
/// (days later, from a Devices screen) when the phrase is long gone. So it
/// keeps THIS instead: the same 32 bytes the config used to carry, in the same
/// container, at the same exposure as before.
///
/// A SECRET both ways: `phrase` is wiped in place on every path, and the caller
/// owns what lands in `out_master_sk`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_master_signing_key_from_phrase_zeroize(
    phrase: *mut u8,
    phrase_len: usize,
    out_master_sk: *mut u8,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe {
        clear_err(err_out);
    }
    if phrase_len > MAX_FFI_CSTR_LEN {
        unsafe {
            write_err(err_out, "phrase too long (>4 KiB)");
        }
        return VEIL_ERR_INVALID_ARG;
    }

    let Some(_guard) = (unsafe { ZeroOnDrop::arm(phrase, phrase_len) }) else {
        unsafe { write_err(err_out, "phrase is NULL or too long (>4 KiB)") };
        return VEIL_ERR_INVALID_ARG;
    };

    // AFTER the guard: a NULL ancillary argument used to return the documented
    // error with the caller's secret still sitting in their memory (report14
    // V14-M14). The secret's own pointer and length are `arm`'s business
    // above; this is only about the rest.
    if phrase.is_null() || out_master_sk.is_null() {
        unsafe {
            write_err(err_out, "phrase or out_master_sk is NULL");
        }
        return VEIL_ERR_INVALID_ARG;
    }

    let bytes = unsafe { std::slice::from_raw_parts(phrase as *const u8, phrase_len) };
    let Ok(text) = std::str::from_utf8(bytes) else {
        unsafe {
            write_err(err_out, "phrase is not valid UTF-8");
        }
        return VEIL_ERR_INVALID_ARG;
    };
    let seed = match veil_identity::master_seed::decode_master_seed_from_phrase(text) {
        Ok(s) => s,
        Err(e) => {
            unsafe {
                write_err(err_out, format!("decode phrase: {e}"));
            }
            return VEIL_ERR;
        }
    };
    let sk = zeroize::Zeroizing::new(veil_crypto::identity::derive_master_sk_ed25519(&seed));
    unsafe {
        std::ptr::copy_nonoverlapping(sk.as_ptr(), out_master_sk, 32);
    }
    VEIL_OK
}

/// Merge a document received from another device, authorising with the master
/// key directly rather than with a node config.
///
/// The sibling that reads the master out of a config works only while the
/// config IS the master. Once a device has a transport key of its own — the
/// change that stops two devices restored from one phrase being one node — the
/// config is a device key and cannot authorise anything.
///
/// `master_sk` is 32 SECRET bytes and is wiped in place before return.
/// `document` may name this device already (adopt) or not (delegate); both are
/// handled, and this device's own subkey index is recorded either way.
#[cfg(feature = "node-embedded")]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_adopt_identity_document_from_master_zeroize(
    master_sk: *mut u8,
    veil_dir: *const u8,
    veil_dir_len: usize,
    document: *const u8,
    document_len: usize,
    key_idx_out: *mut u16,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe {
        clear_err(err_out);
    }

    let Some(_guard) = (unsafe { ZeroOnDrop::arm(master_sk, 32) }) else {
        unsafe { write_err(err_out, "master_sk is NULL or too long (>4 KiB)") };
        return VEIL_ERR_INVALID_ARG;
    };

    // AFTER the guard: a NULL ancillary argument used to return the documented
    // error with the caller's secret still sitting in their memory (report14
    // V14-M14). The secret's own pointer and length are `arm`'s business
    // above; this is only about the rest.
    if master_sk.is_null() || document.is_null() {
        unsafe {
            write_err(err_out, "master_sk or document is NULL");
        }
        return VEIL_ERR_INVALID_ARG;
    }

    let Some(dir_str) = (unsafe { slice_to_str(veil_dir, veil_dir_len) }) else {
        unsafe {
            write_err(err_out, "veil_dir is NULL or invalid UTF-8");
        }
        return VEIL_ERR_INVALID_ARG;
    };
    let mut key = zeroize::Zeroizing::new([0u8; 32]);
    unsafe {
        std::ptr::copy_nonoverlapping(master_sk as *const u8, key.as_mut_ptr(), 32);
    }
    let incoming = unsafe { std::slice::from_raw_parts(document, document_len) };
    let now_unix = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    match veil_identity::sovereign_flow::adopt_identity_document(
        std::path::Path::new(dir_str),
        incoming,
        veil_identity::sovereign_flow::MasterSecret::SigningKey(key),
        now_unix,
        now_unix + VEIL_DEFAULT_RESTORE_VALIDITY_SECS,
    ) {
        Ok(outcome) => {
            if !key_idx_out.is_null() {
                unsafe { *key_idx_out = outcome.key_idx() };
            }
            VEIL_OK
        }
        Err(e) => {
            unsafe {
                write_err(err_out, format!("adopt_identity_document: {e}"));
            }
            VEIL_ERR
        }
    }
}

/// The identity address a signed document names — `BLAKE3(master_pubkey)`,
/// written to `out_node_id` (32 bytes).
///
/// This is the address an identity RECEIVES under, and it is not always the
/// address its node speaks under. A host whose config keypair IS the master —
/// every identity in the field today — sees the same 32 bytes both ways. A host
/// whose device has a transport key of its own does not, and it has to publish
/// its rendezvous ad and poll its mailbox under THIS one, or it waits at an
/// address nobody sends to while looking perfectly reachable.
///
/// Decodes and verifies nothing beyond the encoding: the caller is reading its
/// OWN stored document, which it wrote itself.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_identity_document_node_id(
    document: *const u8,
    document_len: usize,
    out_node_id: *mut u8,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe {
        clear_err(err_out);
    }
    if document.is_null() || out_node_id.is_null() {
        unsafe {
            write_err(err_out, "document or out_node_id is NULL");
        }
        return VEIL_ERR_INVALID_ARG;
    }
    let bytes = unsafe { std::slice::from_raw_parts(document, document_len) };
    match veil_identity::sovereign_flow::document_node_id(bytes) {
        Ok(node_id) => {
            unsafe {
                std::ptr::copy_nonoverlapping(node_id.as_ptr(), out_node_id, 32);
            }
            VEIL_OK
        }
        Err(e) => {
            unsafe {
                write_err(err_out, format!("document decode: {e}"));
            }
            VEIL_ERR
        }
    }
}

/// Restore identity AND write an encrypted master-seed backup
/// ([`veil_restore_identity_from_phrase_zeroize`] + passphrase-protected
/// `master.enc` file in `veil_dir`).
///
/// Both `phrase` AND `password` buffers are zeroed in place before this
/// function returns (on every code path — success, validation error,
/// I/O error, or panic).  Caller still owns the allocations and frees
/// them after this call.
///
/// `password` may be NULL — equivalent to calling
/// [`veil_restore_identity_from_phrase_zeroize`] without the encrypted-
/// master file.  This is provided as a convenience so consumer Flutter
/// apps can branch on "user-supplied passphrase or not" without
/// switching FFI symbols.
///
/// The Argon2id parameters are the spec-production default (64 MiB,
/// t=3, p=4).  Test code wanting cheaper KDF must use the lower-level
/// `veil_identity::sovereign_flow::restore_identity` directly with
/// `argon2_params_override`.
///
/// # Safety
/// `phrase` and (if non-NULL) `password` must each point to a writable buffer
/// of at least the given length.  `veil_dir` and `instance_label` are read-only
/// `(*const u8, len)` UTF-8.  `err_out` must be writable; on non-OK returns it
/// receives a pointer to a malloc'd UTF-8 string — caller frees with
/// [`veil_free_string`].
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_restore_identity_from_phrase_zeroize_with_password(
    phrase: *mut u8,
    phrase_len: usize,
    veil_dir: *const u8,
    veil_dir_len: usize,
    instance_label: *const u8,
    instance_label_len: usize,
    password: *mut u8,
    password_len: usize,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe {
        clear_err(err_out);
    }
    if phrase.is_null() {
        unsafe {
            write_err(err_out, "phrase is NULL");
        }
        return VEIL_ERR_INVALID_ARG;
    }
    if phrase_len > MAX_FFI_CSTR_LEN {
        unsafe {
            write_err(err_out, "phrase too long (>4 KiB)");
        }
        return VEIL_ERR_INVALID_ARG;
    }

    // RAII guards: zero both phrase + password buffers regardless of return
    // path. One guard per buffer because the lengths differ.
    let Some(_phrase_guard) = (unsafe { ZeroOnDrop::arm(phrase, phrase_len) }) else {
        unsafe { write_err(err_out, "phrase is NULL or too long (>4 KiB)") };
        return VEIL_ERR_INVALID_ARG;
    };

    // Read password BEFORE constructing its guard so we can copy it to an owned
    // buffer — the guard scrubs the original caller buffer after we return.
    // Audit L-15: the owned copy is wrapped in `Zeroizing` and moved into
    // `RestoreIdentityOptions.save_encrypted_with_password` (now typed
    // `Option<Zeroizing<Vec<u8>>>`), so it is scrubbed when `opts` drops inside
    // `restore_identity`. The encryption path only BORROWS the password, so this
    // owned copy is the longest-lived plaintext and must wipe itself — the
    // previous plain `Vec<u8>` left it in freed heap, defeating this function's
    // whole purpose.
    let (pw_bytes, _pw_guard) = if password.is_null() {
        (
            None,
            ZeroOnDrop {
                ptr: std::ptr::null_mut(),
                len: 0,
            },
        )
    } else {
        if password_len > MAX_FFI_CSTR_LEN {
            unsafe {
                write_err(err_out, "password too long (>4 KiB)");
            }
            return VEIL_ERR_INVALID_ARG;
        }
        let guard = ZeroOnDrop {
            ptr: password,
            len: password_len,
        };
        let pw_slice = unsafe { std::slice::from_raw_parts(password as *const u8, password_len) };
        let bytes = match std::str::from_utf8(pw_slice) {
            Ok(s) => Some(zeroize::Zeroizing::new(s.as_bytes().to_vec())),
            Err(_) => {
                unsafe {
                    write_err(err_out, "password is not valid UTF-8");
                }
                return VEIL_ERR_INVALID_ARG;
            }
        };
        (bytes, guard)
    };

    let phrase_bytes = unsafe { std::slice::from_raw_parts(phrase as *const u8, phrase_len) };
    let phrase_str = match std::str::from_utf8(phrase_bytes) {
        Ok(s) => s,
        Err(_) => {
            unsafe {
                write_err(err_out, "phrase is not valid UTF-8");
            }
            return VEIL_ERR_INVALID_ARG;
        }
    };
    let Some(dir_str) = (unsafe { slice_to_str(veil_dir, veil_dir_len) }) else {
        unsafe {
            write_err(err_out, "veil_dir is NULL or invalid UTF-8");
        }
        return VEIL_ERR_INVALID_ARG;
    };
    let Some(label_str) = (unsafe { slice_to_str(instance_label, instance_label_len) }) else {
        unsafe {
            write_err(err_out, "instance_label is NULL or invalid UTF-8");
        }
        return VEIL_ERR_INVALID_ARG;
    };

    let master_seed = match veil_identity::master_seed::decode_master_seed_from_phrase(phrase_str) {
        Ok(s) => s,
        Err(e) => {
            unsafe {
                write_err(err_out, format!("decode phrase: {e}"));
            }
            return VEIL_ERR;
        }
    };

    let now_unix = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    let opts = veil_identity::sovereign_flow::RestoreIdentityOptions {
        veil_dir: std::path::PathBuf::from(dir_str),
        master: veil_identity::sovereign_flow::MasterRecovery::Seed(master_seed),
        save_encrypted_with_password: pw_bytes,
        argon2_params_override: None,
        instance_label: label_str.chars().take(64).collect::<String>(),
        pow_difficulty: 0,
        now_unix,
        valid_until_unix: now_unix + VEIL_DEFAULT_RESTORE_VALIDITY_SECS,
        algo: veil_types::SignatureAlgorithm::Ed25519,
        master_falcon_keypair_bytes: None,
        device_sk_seed: None,
    };

    match veil_identity::sovereign_flow::restore_identity(opts) {
        Ok(_output) => VEIL_OK,
        Err(e) => {
            unsafe {
                write_err(err_out, format!("restore_identity: {e}"));
            }
            VEIL_ERR
        }
    }
}

