unsafe fn write_err(err_out: *mut *mut c_char, msg: impl Into<String>) {
    if err_out.is_null() {
        return;
    }
    let cs = CString::new(msg.into())
        .unwrap_or_else(|_| CString::new("<error message contained NUL>").unwrap());
    unsafe {
        *err_out = cs.into_raw();
    }
}

unsafe fn clear_err(err_out: *mut *mut c_char) {
    if !err_out.is_null() {
        unsafe {
            *err_out = ptr::null_mut();
        }
    }
}

/// Maximum length for a caller-supplied text input on the FFI boundary.
///
/// All text inputs use the explicit-length `(*const u8, len)` ABI
/// ([`slice_to_str`] / [`opt_slice_to_str`]): the length is authoritative, so
/// there is no `strnlen` scan and no "must be NUL-terminated or readable for
/// 4 KiB" footgun. This cap is a sanity/DoS bound — 4 KiB covers every
/// legitimate input shape: filesystem paths (Linux PATH_MAX = 4096), BIP-39
/// phrases (~330 B for 24 words), passwords (typically <256 B), invite URIs
/// (<1 KiB). Inputs longer than this are rejected as invalid.
const MAX_FFI_CSTR_LEN: usize = 4096;

/// Decode a REQUIRED text input from an explicit `(ptr, len)` byte pair — the
/// length-based C ABI used for every caller-supplied string.
///
/// Unlike the `strnlen` path, the length is authoritative: there is no scan and
/// no "must be NUL-terminated or readable for 4 KiB" footgun — a non-terminated
/// buffer of exactly `len` bytes is well-defined. Returns `None` when `ptr` is
/// NULL, `len` exceeds [`MAX_FFI_CSTR_LEN`], or the bytes are not valid UTF-8.
/// An empty input (`len == 0`, non-NULL `ptr`) decodes to `Some("")`; callers
/// that forbid empty validate that themselves.
///
/// # Safety
/// `ptr` is NULL, or points to a readable buffer of at least `len` bytes. No
/// NUL terminator is required or consulted.
unsafe fn slice_to_str<'a>(ptr: *const u8, len: usize) -> Option<&'a str> {
    if ptr.is_null() || len > MAX_FFI_CSTR_LEN {
        return None;
    }
    let bytes = unsafe { std::slice::from_raw_parts(ptr, len) };
    std::str::from_utf8(bytes).ok()
}

/// Tri-state decode of an OPTIONAL text input from `(ptr, len)`, for any
/// nullable string (`password`, `instance_label`, …):
///  * NULL `ptr` → `Ok(None)` (argument omitted),
///  * valid UTF-8 within [`MAX_FFI_CSTR_LEN`] → `Ok(Some(s))`,
///  * non-NULL but invalid UTF-8 or over-cap → `Err(())` (caller MUST reject,
///    never silently coerce to "omitted" — see diff-audit M26).
///
/// # Safety
/// `ptr` is NULL, or points to a readable buffer of at least `len` bytes.
unsafe fn opt_slice_to_str<'a>(ptr: *const u8, len: usize) -> Result<Option<&'a str>, ()> {
    if ptr.is_null() {
        return Ok(None);
    }
    if len > MAX_FFI_CSTR_LEN {
        return Err(());
    }
    let bytes = unsafe { std::slice::from_raw_parts(ptr, len) };
    std::str::from_utf8(bytes).map(Some).map_err(|_| ())
}

/// Non-elidable wipe of a caller-owned byte buffer at the FFI boundary.
///
/// The secret-scrub `ZeroOnDrop` guards below wipe caller buffers (BIP-39
/// phrases, passwords) that Rust never reads again. A plain `write_bytes`
/// (memset) on a never-again-read buffer is a dead store the optimizer is
/// permitted to ELIDE — defeating the very scrub the guard exists for. Writing
/// each byte through `write_volatile` forbids elision, and the `compiler_fence`
/// keeps the stores from being reordered past the guard's drop. NULL `ptr` (or
/// `len == 0`) is a no-op.
///
/// # Safety
/// `ptr` must be valid for writes of `len` bytes, or be NULL.
unsafe fn volatile_wipe(ptr: *mut u8, len: usize) {
    if ptr.is_null() {
        return;
    }
    for i in 0..len {
        unsafe { core::ptr::write_volatile(ptr.add(i), 0u8) };
    }
    core::sync::atomic::compiler_fence(core::sync::atomic::Ordering::SeqCst);
}

/// Zero a caller-owned secret buffer no matter how the call returns.
///
/// ARMED FIRST, before any other argument is looked at. That ordering is the
/// whole contract: ten entry points used to validate their ancillary
/// arguments — a document pointer, a device id, a TOML blob — and return the
/// documented error while the phrase or the private config the caller had just
/// handed over stayed in that caller's memory. xVeil wipes its own buffer in a
/// `finally` and never noticed; a standalone C caller following the header has
/// no such second line of defence (report14 V14-M14).
///
/// One type rather than ten identical local copies, for the same reason
/// `bytes_to_hex` replaced its seven: a rule that is written down once cannot
/// be got wrong in the tenth place.
struct ZeroOnDrop {
    ptr: *mut u8,
    len: usize,
}

impl ZeroOnDrop {
    /// Arm the guard, or refuse the buffer.
    ///
    /// `None` is "this is not a buffer this ABI can scrub as documented" — a
    /// NULL pointer, or a length past [`MAX_FFI_CSTR_LEN`], which is rejected
    /// BEFORE anything touches it. The caller turns that into
    /// `VEIL_ERR_INVALID_ARG`.
    ///
    /// # Safety
    /// `ptr` must be valid for writes of `len` bytes, or be NULL.
    unsafe fn arm(ptr: *mut u8, len: usize) -> Option<Self> {
        if ptr.is_null() || len > MAX_FFI_CSTR_LEN {
            return None;
        }
        Some(Self { ptr, len })
    }
}

impl Drop for ZeroOnDrop {
    fn drop(&mut self) {
        unsafe { volatile_wipe(self.ptr, self.len) };
    }
}

/// detect FFI re-entry from inside a Tokio worker
/// thread (e.g. from a recv-handler callback) and refuse to proceed.
///
/// Returns `true` iff the current thread is already executing inside a
/// Tokio runtime context. Calling `runtime.block_on(...)` or
/// `tokio_mutex.blocking_lock` from such a thread would deadlock the
/// worker. Every FFI entry point that performs a synchronous
/// `block_on` must call this before doing so and surface
/// [`VEIL_ERR_REENTRANT`] when it returns `true`.
fn in_tokio_runtime() -> bool {
    tokio::runtime::Handle::try_current().is_ok()
}

/// Steps 1 + 2a of the callback-quiescence protocol shared by [`veil_close`]
/// and [`veil_app_close`] (audit V-01), in the one order that is correct:
///
/// 1. **Retire the callback slot.** From this instant the dispatch loop can no
///    longer reach the host: a message it dequeues next reads `None` and takes
///    its `continue` arm, before any callee-owned buffer is allocated.
/// 2. **Take and abort the task.** `abort()` is only a request — the dispatch
///    sections of both loops (slot read → buffer alloc → C call) contain no
///    `.await`, so a cancellation that arrives inside one lands only at the
///    following await point, i.e. *after* the callback has already run.
///
/// Returned is the `JoinHandle` the caller must still await (step 2b) — that
/// await is the observation which proves the task has actually stopped.
/// Splitting there is deliberate: the two callers await it differently (inline
/// `block_on` vs deferred `spawn`, see [`in_tokio_runtime`]), but neither may
/// vary the order above, so the order lives here rather than at the call sites.
fn retire_dispatch_callback<T>(
    cb_slot: &StdMutex<Option<T>>,
    task_slot: &StdMutex<Option<tokio::task::JoinHandle<()>>>,
) -> Option<tokio::task::JoinHandle<()>> {
    *cb_slot.lock().unwrap_or_else(|e| e.into_inner()) = None;
    let task = task_slot.lock().unwrap_or_else(|e| e.into_inner()).take();
    if let Some(task) = &task {
        task.abort();
    }
    task
}

/// Step 2b of the same protocol: wait for the retired task to have actually
/// stopped, then run `tail` (the remaining close work, e.g. the APP_UNBIND).
///
/// Awaiting an aborted `JoinHandle` resolves precisely when the task is no
/// longer running — including when the cancellation arrived while the task was
/// inside a dispatch section it could not be interrupted in. That observation,
/// not the `abort()` before it, is what lets the host free its trampoline the
/// moment the close call returns.
///
/// Returns `true` when the wait completed synchronously. A caller already
/// inside a Tokio runtime cannot wait — `block_on` on the runtime driving the
/// caller deadlocks the worker — so for that caller the join and `tail` are
/// deferred onto the runtime and `false` is returned. Callers on that path get
/// only the step-1 guarantee (no NEW dispatch), never the quiescence one; no
/// supported host reaches it (Dart calls FFI on its isolate thread, never a
/// tokio worker) and it exists so misuse degrades instead of hanging.
fn await_retired_task(
    runtime: &tokio::runtime::Runtime,
    task: Option<tokio::task::JoinHandle<()>>,
    tail: impl std::future::Future<Output = ()> + Send + 'static,
) -> bool {
    let body = async move {
        if let Some(task) = task {
            // `Err` here is the expected `JoinError::Cancelled` from the abort
            // in step 2a (or a panic the task already reported); either way
            // the task has stopped, which is the only thing being awaited for.
            let _ = task.await;
        }
        tail.await;
    };
    if in_tokio_runtime() {
        runtime.spawn(body);
        false
    } else {
        runtime.block_on(body);
        true
    }
}

/// Build a tokio multi-threaded runtime sized for mobile/desktop hosts.
///
/// Worker threads = `min(cpu_count, 4)` — small enough to keep RSS low
/// on a budget Android device, large enough to overlap I/O on multi-core.
/// Test-only since `8e1f5c00` gave every handle a single-worker runtime of its
/// own: production takes `build_runtime_with(1)` and nothing else asks for the
/// sized pool. The tests still want a multi-worker runtime to overlap I/O.
#[cfg(test)]
fn build_runtime() -> Result<tokio::runtime::Runtime, std::io::Error> {
    let workers = std::thread::available_parallelism()
        .map(|n| n.get().min(4))
        .unwrap_or(2);
    build_runtime_with(workers)
}

/// One worker, for a HANDLE runtime.
///
/// Every [`veil_connect`] handle carries its own runtime, and an app holds
/// several handles at once — sampled live: six handles, six runtimes,
/// twenty-four permanent `veil-ffi` worker threads, every one parked. This
/// read for months as "the blocking pool never drains"; the stacks say
/// otherwise — they are ordinary runtime workers, multiplied by handles.
/// A handle is a thin IPC client: `block_on` request/response plus one
/// event-stream task, which one worker drives fine. The full-size builder
/// stays for anything that genuinely computes.
fn build_handle_runtime() -> Result<tokio::runtime::Runtime, std::io::Error> {
    build_runtime_with(1)
}

fn build_runtime_with(workers: usize) -> Result<tokio::runtime::Runtime, std::io::Error> {
    tokio::runtime::Builder::new_multi_thread()
        .worker_threads(workers)
        .enable_all()
        .thread_name("veil-ffi")
        .build()
}

