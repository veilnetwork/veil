pub const VEIL_EVENT_MAILBOX_WAKE: u8 = 5;

/// Push-event callback. Invoked from a tokio worker thread for every
/// `LocalAppMsg::Event` frame the daemon emits while this handler is
/// installed. `payload`+`payload_len` describe the per-kind opaque
/// bytes (see. `veil_proto::event_kind` for wire format per kind).
///
/// BUFFER OWNERSHIP (cycle-7 H6): for a non-empty payload the pointer is an
/// OWNED heap buffer the callee must free via `veil_free_buf(payload,
/// payload_len)` after copying — it MAY be retained past this synchronous call
/// (Dart `NativeCallable.listener`). An empty payload passes a NULL pointer with
/// `payload_len == 0` (nothing to free).
///
/// wrapped in `Option<...>` for safe
/// NULL-pointer rejection at the FFI boundary. See [`VeilRecvCb`]
/// docs.
pub type VeilEventCb = Option<
    unsafe extern "C" fn(
        user: *mut std::ffi::c_void,
        kind: u8,
        payload: *const u8,
        payload_len: size_t,
    ),
>;

/// A currently-installed event callback plus its opaque `user` pointer,
/// transported as `usize` so the slot is `Send`. Event analogue of
/// [`RecvCbSlot`]: the event task re-reads it per event so [`veil_close`] can
/// retire the handler by clearing the slot BEFORE it aborts the task (audit
/// V-01). Capturing `cb_fn` directly in the task — as this loop used to — left
/// no way to retire it, so the only tool close had was an `abort()` that does
/// not land inside a dispatch section.
#[derive(Clone, Copy)]
struct EventCbSlot {
    cb: unsafe extern "C" fn(*mut std::ffi::c_void, u8, *const u8, size_t),
    user_addr: usize,
}

/// Install a push-event handler on this veil connection
///. The handler runs on a private tokio task and is
/// torn down when the handle is closed or `set_event_handler` is
/// called again. Returns [`VEIL_OK`] iff a fresh handler was
/// installed; [`VEIL_ERR_INVALID_ARG`] if `handle` is NULL.
///
/// Single-subscriber semantics — calling this twice replaces the
/// previous handler (the prior task is aborted). Pass NULL `user`
/// if the C side does not need the opaque pointer; otherwise the
/// caller must keep `user` valid until the handler is replaced or
/// the handle is closed.
///
/// Threading note: the callback fires on a tokio worker thread.
/// Hosts that marshal to a single-threaded UI loop (Flutter
/// dart:ffi, Swift, Kotlin) should wrap their callback in a
/// listener-style trampoline that wakes the UI isolate/queue.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_set_event_handler(
    handle: *mut VeilHandle,
    cb: VeilEventCb,
    user: *mut std::ffi::c_void,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe {
        clear_err(err_out);
    }
    if handle.is_null() {
        unsafe {
            write_err(err_out, "handle is NULL");
        }
        return VEIL_ERR_INVALID_ARG;
    }
    // audit: NULL callback → Some(_) match (see VeilRecvCb).
    let cb_fn = match cb {
        Some(f) => f,
        None => {
            unsafe {
                write_err(err_out, "callback is NULL");
            }
            return VEIL_ERR_INVALID_ARG;
        }
    };
    get_or_return!(
        h_ref,
        handle_table(),
        handle,
        err_out,
        VEIL_ERR_INVALID_ARG,
        "VeilHandle"
    );
    // Install/replace the callback by swapping the shared slot the task reads
    // per event (audit V-01) — the same shape `veil_app_set_recv_handler`
    // uses. It is also what `veil_close` retires before aborting the task.
    {
        let mut slot = h_ref.event_cb.lock().unwrap_or_else(|e| e.into_inner());
        *slot = Some(EventCbSlot {
            // FFI pointers are not Send — transport `user` as `usize`.
            cb: cb_fn,
            user_addr: user as usize,
        });
    }
    // Cancel any previous handler before subscribing again. A second
    // subscriber would replace the SDK-side mpsc sink anyway, but we
    // also want to drop the old task so it stops holding the runtime
    // worker and any captured pointers.
    if let Ok(mut guard) = h_ref.event_task.lock()
        && let Some(prev) = guard.take()
    {
        prev.abort();
    }
    let bundle = Arc::clone(&h_ref.bundle);
    let bundle_for_task = Arc::clone(&bundle);
    let cb_cell = Arc::clone(&h_ref.event_cb);
    let task = bundle.runtime.spawn(async move {
        let bundle = bundle_for_task;
        // Subscribe inside the task so the SDK-side mpsc sender is
        // installed under the same lock that `events` takes — avoids
        // a race with simultaneous `events` callers (the doc contract
        // says single-subscriber, so racing would already be UB on
        // the consumer side, but this keeps the daemon-side behaviour
        // deterministic).
        let events = {
            let client = bundle.client.lock().await;
            client.events().await
        };
        run_event_dispatch_loop(events, cb_cell).await;
    });
    if let Ok(mut guard) = h_ref.event_task.lock() {
        *guard = Some(task);
    }
    VEIL_OK
}

/// The persistent push-event dispatch loop: drain `events`, hand each one to
/// whatever callback currently sits in `cb_cell`.
///
/// Standalone (rather than inline in the spawned task) for the same reason as
/// [`run_recv_dispatch_loop`] — so the close protocol is tested against the
/// real loop.
async fn run_event_dispatch_loop(
    mut events: mpsc::Receiver<veilclient::VeilEvent>,
    cb_cell: Arc<StdMutex<Option<EventCbSlot>>>,
) {
    while let Some(ev) = events.recv().await {
        // Copy the current callback out of the slot; never hold the lock
        // across the C callback. A retired slot (`veil_close` step 1)
        // drops the event BEFORE the callee-owned buffer below is even
        // allocated — no dangling trampoline call, no orphaned buffer.
        let Some(EventCbSlot {
            cb: cb_fn,
            user_addr,
        }) = *cb_cell.lock().unwrap_or_else(|e| e.into_inner())
        else {
            continue;
        };
        let user_ptr = user_addr as *mut std::ffi::c_void;
        let kind = ev.kind;
        let payload_len = ev.payload.len();
        // cycle-7 H6: same use-after-free hazard as the recv loop — the host
        // callback may read `payload_ptr` after this frame returns (Dart
        // `NativeCallable.listener`). For a non-empty payload, hand the callee
        // an OWNED heap copy it frees via `veil_free_buf(payload_ptr,
        // payload_len)`; an empty payload passes NULL (nothing to free).
        let base: *mut u8 = if payload_len == 0 {
            std::ptr::null_mut()
        } else {
            Box::into_raw(ev.payload.into_boxed_slice()).cast()
        };
        // catch_unwind around the callback so
        // a panic doesn't unwind across the C-ABI frame
        // (UB). Logged and the event-stream stays alive.
        let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| unsafe {
            cb_fn(user_ptr, kind, base.cast_const(), payload_len);
        }));
        if result.is_err() {
            // Reclaim on the unwinding (dev/test) path so we don't leak.
            if !base.is_null() {
                unsafe {
                    drop(Box::from_raw(std::ptr::slice_from_raw_parts_mut(
                        base,
                        payload_len,
                    )));
                }
            }
            ffi_diag(
                "[veilclient-ffi] event-handler callback panicked; \
                 event dropped, stream kept open",
            );
        }
        // Loop continues until channel closes (None from recv).
    }
}

// ── Identity restore ────────────────────────────────────────────

/// Maximum freshness window for a restored IdentityDocument — 30 days.
/// Mirrors `veil_identity::MAX_FRESHNESS_WINDOW_SECS`. Restored
/// devices typically request the full window so the doc lives through
/// the next routine document republish (default ~half-life).
pub const VEIL_DEFAULT_RESTORE_VALIDITY_SECS: u64 = 30 * 24 * 3600;

// ── zeroize-on-consume BIP-39 variants ────────────────
//
// The phrase is a SECRET (24-word master seed). These entry points take it as
// a writable `(*mut u8, len)` buffer and overwrite every byte with `0` after
// decoding — on success and on every error path — so a host that loads the
// seed via a malloc'd buffer (typical Flutter `Uint8List` / `calloc<Uint8>`)
// does not leave the plaintext lingering in the heap. Caller still owns the
// allocation and frees the (now-zeroed) buffer.
//
// (The earlier non-zeroizing `*const c_char` forms were removed in the
// explicit-length ABI migration — they left the mnemonic in caller memory.)

/// Generate a FRESH master identity phrase: a new random 32-byte master seed
/// encoded as the 24-word English mnemonic (veil master-phrase checksum). The
/// seed material lives only inside this call and zeroizes on drop — the
/// returned phrase is its ONLY representation. Flow: show it to the user for
/// the paper backup, confirm, then create the identity DETERMINISTICALLY via
/// `veil_restore_identity_from_phrase_zeroize` with this same phrase, so a
/// fresh onboarding and a later disaster-recovery restore agree on node_id.
///
/// On success writes a NUL-terminated UTF-8 phrase into `*phrase_out`; the
/// caller MUST free it with `veil_free_string`, and should zero the buffer
/// first (the Dart wrapper copies into an immutable String and scrubs the
/// native bytes — same posture as the validate/restore zeroize variants).
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_generate_master_phrase(
    phrase_out: *mut *mut c_char,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe {
        clear_err(err_out);
    }
    if phrase_out.is_null() {
        unsafe {
            write_err(err_out, "phrase_out is NULL");
        }
        return VEIL_ERR_INVALID_ARG;
    }
    let seed = veil_identity::master_seed::generate_master_seed();
    let mnemonic = match veil_identity::master_seed::encode_master_seed_to_phrase(&seed) {
        Ok(m) => m,
        Err(e) => {
            unsafe {
                write_err(err_out, format!("phrase encode failed: {e}"));
            }
            return VEIL_ERR;
        }
    };
    // The intermediate String zeroizes on drop; the CString we hand out is the
    // caller's to scrub + free (veil_free_string).
    let phrase = zeroize::Zeroizing::new(mnemonic.to_string());
    let cs = match CString::new(phrase.as_str()) {
        Ok(c) => c,
        Err(_) => {
            unsafe {
                write_err(err_out, "phrase contained NUL");
            }
            return VEIL_ERR;
        }
    };
    unsafe {
        *phrase_out = cs.into_raw();
    }
    VEIL_OK
}

/// Validate a BIP-39 master phrase, zeroizing the caller's buffer on consume.
///
/// Returns `VEIL_OK` iff the phrase is exactly 24 words from the English BIP-39
/// wordlist AND the checksum verifies. The `(phrase, phrase_len)` buffer is
/// overwritten with `0` before returning, on every path. UI uses this for live
/// feedback as the user types.
///
/// Reads the phrase, runs the same validation, and unconditionally
/// overwrites the buffer bytes with `0` before returning — regardless
/// of success or failure. Caller MUST guarantee `phrase` points to a
/// writable, NUL-terminated UTF-8 buffer (typical: malloc'd from C, or
/// `String.toNativeUtf8` in Dart).
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_validate_bip39_phrase_zeroize(
    phrase: *mut u8,
    phrase_len: usize,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe {
        clear_err(err_out);
    }
    if phrase.is_null() {
        unsafe {
            write_err(err_out, "phrase is NULL");
        }
        return VEIL_ERR_INVALID_ARG;
    }
    // Explicit-length ABI: the caller hands us the exact buffer length, so we
    // can scrub it precisely without a strnlen scan (and even if the bytes are
    // not UTF-8). Reject an over-cap length before touching memory.
    if phrase_len > MAX_FFI_CSTR_LEN {
        unsafe {
            write_err(err_out, "phrase too long (>4 KiB)");
        }
        return VEIL_ERR_INVALID_ARG;
    }
    // RAII guard: zero the WHOLE caller buffer on EVERY return path — success,
    // decode failure, or non-UTF-8 — so possibly-sensitive input never lingers.
    // Mirrors `veil_restore_identity_from_phrase_zeroize`.
    let Some(_guard) = (unsafe { ZeroOnDrop::arm(phrase, phrase_len) }) else {
        unsafe { write_err(err_out, "phrase is NULL or too long (>4 KiB)") };
        return VEIL_ERR_INVALID_ARG;
    };

    // UTF-8 decode AFTER the guard is armed.
    let phrase_bytes = unsafe { std::slice::from_raw_parts(phrase as *const u8, phrase_len) };
    let phrase_str = match std::str::from_utf8(phrase_bytes) {
        Ok(s) => s,
        Err(_) => {
            unsafe {
                write_err(err_out, "phrase is not valid UTF-8");
            }
            return VEIL_ERR_INVALID_ARG;
        }
    };
    match veil_identity::master_seed::decode_master_seed_from_phrase(phrase_str) {
        Ok(_seed) => VEIL_OK,
        Err(e) => {
            unsafe {
                write_err(err_out, format!("invalid phrase: {e}"));
            }
            VEIL_ERR
        }
    }
}

/// Restore an identity from a BIP-39 master phrase, zeroizing the phrase on
/// consume.
///
/// Decodes `phrase` → master_seed → derives identity_sk → builds a fresh signed
/// `IdentityDocument` and writes `identity_document.bin`, `instance.toml`, and
/// `identity_sk.bin` to `veil_dir`. `instance_label` is the human-readable
/// device name (capped at 64 chars). Idempotent: same phrase + same `veil_dir`
/// regenerates the per-device key; the `node_id` (= BLAKE3(master_pk)) is stable.
///
/// `phrase` is a SECRET, passed as a writable `(*mut u8, len)` buffer that is
/// overwritten with `0` before return on EVERY path. `veil_dir` and
/// `instance_label` are non-secret `(*const u8, len)` UTF-8. Returns `VEIL_OK`
/// on success; on failure sets `*err_out` and returns `VEIL_ERR`.
/// The body of both restore entry points, differing only in whether the host
/// had a node key to offer. See `device_sk_seed` below.
// The same pointer/length pairs the public wrappers take, plus the optional
// device seed that tells the two entry points apart — see `bind_internal` and
// `mailbox_put_inner` for the same shape and the same reason.
#[allow(clippy::too_many_arguments)]
unsafe fn restore_from_phrase_inner(
    device_seed: Option<zeroize::Zeroizing<[u8; 32]>>,
    // The identity's Falcon master half, framed as `master_falcon.bin` is.
    // `Some` makes this a HYBRID provisioning: `node_id` is then BLAKE3 over
    // the whole 929-byte master, not over its Ed25519 half, so the two are
    // different identities and the caller must mean the one it asks for.
    falcon_bundle: Option<Vec<u8>>,
    phrase: *mut u8,
    phrase_len: usize,
    veil_dir: *const u8,
    veil_dir_len: usize,
    instance_label: *const u8,
    instance_label_len: usize,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe {
        clear_err(err_out);
    }
    if phrase.is_null() {
        unsafe {
            write_err(err_out, "phrase is NULL");
        }
        return VEIL_ERR_INVALID_ARG;
    }
    // Explicit-length ABI: the length is authoritative, so we scrub exactly the
    // caller's buffer with no strnlen scan. Reject over-cap before touching it.
    if phrase_len > MAX_FFI_CSTR_LEN {
        unsafe {
            write_err(err_out, "phrase too long (>4 KiB)");
        }
        return VEIL_ERR_INVALID_ARG;
    }

    // RAII guard: zero the WHOLE caller buffer no matter how this returns
    // (early return on validation error, panic, success).
    let Some(_guard) = (unsafe { ZeroOnDrop::arm(phrase, phrase_len) }) else {
        unsafe { write_err(err_out, "phrase is NULL or too long (>4 KiB)") };
        return VEIL_ERR_INVALID_ARG;
    };

    // UTF-8 decode AFTER guard armed, so a non-UTF8 phrase still gets
    // scrubbed (possibly-sensitive bytes from a user input field).
    let phrase_bytes = unsafe { std::slice::from_raw_parts(phrase as *const u8, phrase_len) };
    let phrase_str = match std::str::from_utf8(phrase_bytes) {
        Ok(s) => s,
        Err(_) => {
            unsafe {
                write_err(err_out, "phrase is not valid UTF-8");
            }
            return VEIL_ERR_INVALID_ARG;
        }
    };
    let Some(dir_str) = (unsafe { slice_to_str(veil_dir, veil_dir_len) }) else {
        unsafe {
            write_err(err_out, "veil_dir is NULL or invalid UTF-8");
        }
        return VEIL_ERR_INVALID_ARG;
    };
    let Some(label_str) = (unsafe { slice_to_str(instance_label, instance_label_len) }) else {
        unsafe {
            write_err(err_out, "instance_label is NULL or invalid UTF-8");
        }
        return VEIL_ERR_INVALID_ARG;
    };

    let master_seed = match veil_identity::master_seed::decode_master_seed_from_phrase(phrase_str) {
        Ok(s) => s,
        Err(e) => {
            unsafe {
                write_err(err_out, format!("decode phrase: {e}"));
            }
            return VEIL_ERR;
        }
    };

    let now_unix = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    let opts = veil_identity::sovereign_flow::RestoreIdentityOptions {
        veil_dir: std::path::PathBuf::from(dir_str),
        master: veil_identity::sovereign_flow::MasterRecovery::Seed(master_seed),
        save_encrypted_with_password: None,
        argon2_params_override: None,
        instance_label: label_str.chars().take(64).collect::<String>(),
        pow_difficulty: 0,
        now_unix,
        valid_until_unix: now_unix + VEIL_DEFAULT_RESTORE_VALIDITY_SECS,
        algo: if falcon_bundle.is_some() {
            veil_types::SignatureAlgorithm::Ed25519Falcon512Hybrid
        } else {
            veil_types::SignatureAlgorithm::Ed25519
        },
        master_falcon_keypair_bytes: falcon_bundle,
        // ADOPT THE NODE'S OWN KEY when the host offers one, so the document
        // names the key this device actually signs and handshakes with.
        //
        // A restore otherwise generates a fresh random device key, and a host
        // that already mined a node identity then has TWO: the node signs with
        // one and the document vouches for the other. Every signature the
        // device makes fails its own author binding after that, silently — the
        // message is stored, filtered out of every read and skipped by every
        // send, with nothing anywhere saying why. Measured on a two-device
        // stand: node key cdbbaa51…, document subkey 507614a8…, and the
        // device's own posts invisible on the device that wrote them.
        device_sk_seed: device_seed,
    };

    match veil_identity::sovereign_flow::restore_identity(opts) {
        Ok(_output) => VEIL_OK,
        Err(e) => {
            unsafe {
                write_err(err_out, format!("restore_identity: {e}"));
            }
            VEIL_ERR
        }
    }
}

/// Restore an identity from a BIP-39 phrase, generating this device's key.
///
/// The original entry point, unchanged, for a host with no node identity of its
/// own to offer. Every host that has already mined a node has one — see
/// `veil_restore_identity_from_phrase_zeroize_with_node_key`.
///
/// # Safety
/// As the with-node-key form, minus the TOML argument.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_restore_identity_from_phrase_zeroize(
    phrase: *mut u8,
    phrase_len: usize,
    veil_dir: *const u8,
    veil_dir_len: usize,
    instance_label: *const u8,
    instance_label_len: usize,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe {
        restore_from_phrase_inner(
            None,
            None,
            phrase,
            phrase_len,
            veil_dir,
            veil_dir_len,
            instance_label,
            instance_label_len,
            err_out,
        )
    }
}

/// Restore an identity and name THE HOST'S OWN NODE KEY as this device's
/// subkey, taken from `identity_toml` — the config the node boots on.
///
/// A restore otherwise mints a fresh random device key, which on a host that
/// has already mined a node identity leaves TWO keys for one device: the node
/// signs and handshakes with one, the identity document vouches for the other.
/// Every signature the device makes then fails its own author binding, and does
/// so in silence — the message is stored, filtered out of every read and
/// skipped by every send, with nothing saying why. Measured on a two-device
/// stand as a device whose own posts were invisible on the device that wrote
/// them.
///
/// Naming the node's key collapses the two, so "this device" stops meaning two
/// different things. Nothing about the identity changes: the node_id is still
/// BLAKE3(master_pk) and the master still signs the subkey — only WHICH subkey.
///
/// `identity_toml` carries the node's private key and is NOT zeroized here: the
/// caller owns those bytes and holds them for the life of the node anyway.
/// `phrase` is zeroized exactly as in the other entry point.
///
/// # Safety
/// `phrase` must be writable for `phrase_len`; `veil_dir`, `instance_label` and
/// `identity_toml` readable for their lengths; `err_out` a writable slot.
// Behind `node-embedded`, like `master_signing_key_from_config` below and for
// the same reason: this entry point reads the node's own config, and
// `veil-cfg` is an OPTIONAL dependency that only that feature pulls in. Added
// without the gate, it compiled everywhere xVeil builds — which always turns
// the feature on — and broke a plain `cargo clippy --workspace` that nothing
// had run since the hygiene gate started failing at `cargo fmt`.
#[cfg(feature = "node-embedded")]
/// Provision this device under a HYBRID sovereign identity, taking the master
/// from the identity's encrypted credential.
///
/// The identity this writes is named by the WHOLE master — `node_id` is
/// BLAKE3 over `ed25519 ‖ falcon512`, 929 bytes — so it is a different
/// identity from the one the same phrase produces on its own. That is the
/// point: the Ed25519 half is reproducible from the phrase and the Falcon half
/// is not, so an identity rooted in both cannot be restored from the words
/// alone, and the credential is what restores it.
///
/// The credential goes in, not the key. `credential` is the stored XVSB or
/// XVRC blob and `secret` the phrase or recovery code that opens it; the
/// master is assembled inside and never crosses back. `secret` is a writable
/// buffer, wiped on every return path, exactly like `phrase` elsewhere.
///
/// `identity_toml` is THE KEY THIS DEVICE ALREADY RUNS ON — the same reason
/// `veil_restore_identity_from_phrase_zeroize_with_node_key` takes it. Without
/// it the provisioning mints a second device key and names that one, while the
/// node goes on signing with its own, and every signature fails its own author
/// binding in silence.
///
/// # Safety
/// `credential` readable for `credential_len`; `secret` writable for
/// `secret_len`; `veil_dir`, `instance_label` and `identity_toml` readable for
/// their lengths; `err_out` a writable slot.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_provision_hybrid_identity_from_credential_zeroize(
    credential: *const u8,
    credential_len: usize,
    secret: *mut u8,
    secret_len: usize,
    veil_dir: *const u8,
    veil_dir_len: usize,
    instance_label: *const u8,
    instance_label_len: usize,
    identity_toml: *const u8,
    identity_toml_len: usize,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe { clear_err(err_out) };
    // Armed before anything can refuse: every early return below used to be a
    // path that left the caller's secret in memory.
    let Some(_secret_guard) = (unsafe { ZeroOnDrop::arm(secret, secret_len) }) else {
        unsafe { write_err(err_out, "secret is NULL or too long (>4 KiB)") };
        return VEIL_ERR_INVALID_ARG;
    };
    if credential.is_null() || credential_len == 0 {
        unsafe { write_err(err_out, "credential is NULL or empty") };
        return VEIL_ERR_INVALID_ARG;
    }
    let credential_bytes = unsafe { std::slice::from_raw_parts(credential, credential_len) };
    let secret_bytes = unsafe { std::slice::from_raw_parts(secret, secret_len) };

    // XVSB opens with the phrase, XVRC with its own high-entropy code. Which
    // one this is, is in the blob — not something the caller has to declare
    // and could get wrong.
    let material = if credential_bytes.starts_with(b"XVRC") {
        veil_identity::sovereign_bundle::open_recovery_certificate(credential_bytes, secret_bytes)
    } else {
        veil_identity::sovereign_bundle::open(credential_bytes, secret_bytes)
    };
    let material = match material {
        Ok(m) => m,
        Err(e) => {
            unsafe { write_err(err_out, format!("credential did not open: {e}")) };
            return VEIL_ERR_INVALID_ARG;
        }
    };
    let Some(falcon_bundle) = material.master_falcon_bundle() else {
        unsafe {
            write_err(
                err_out,
                "this credential is not Ed25519+Falcon-512, so it names no hybrid master",
            )
        };
        return VEIL_ERR_INVALID_ARG;
    };

    let Some(toml_str) = (unsafe { slice_to_str(identity_toml, identity_toml_len) }) else {
        unsafe { write_err(err_out, "identity_toml is NULL or invalid UTF-8") };
        return VEIL_ERR_INVALID_ARG;
    };
    let config = match veil_cfg::parse_toml_str(toml_str) {
        Ok(c) => c,
        Err(e) => {
            unsafe { write_err(err_out, format!("identity_toml parse failed: {e}")) };
            return VEIL_ERR_INVALID_ARG;
        }
    };
    let Some(identity) = config.identity else {
        unsafe { write_err(err_out, "identity_toml carries no [identity]") };
        return VEIL_ERR_INVALID_ARG;
    };
    if identity.algo != veil_types::SignatureAlgorithm::Ed25519 {
        unsafe {
            write_err(
                err_out,
                "only an Ed25519 node key can be named as a device subkey",
            )
        };
        return VEIL_ERR_INVALID_ARG;
    }
    use base64::{Engine as _, engine::general_purpose::STANDARD};
    let device_seed = match STANDARD.decode(identity.private_key.as_bytes()) {
        Ok(bytes) if bytes.len() == 32 => {
            let mut seed = [0u8; 32];
            seed.copy_from_slice(&bytes);
            zeroize::Zeroizing::new(seed)
        }
        _ => {
            unsafe { write_err(err_out, "identity_toml key is not a 32-byte Ed25519 seed") };
            return VEIL_ERR_INVALID_ARG;
        }
    };

    // The Ed25519 half still comes from the phrase, which is what makes the
    // two halves one master rather than two keys that happen to travel
    // together. For an XVRC credential the secret is a code and not a phrase,
    // and that case is refused here rather than silently provisioning a
    // different identity.
    unsafe {
        restore_from_phrase_inner(
            Some(device_seed),
            Some(falcon_bundle.to_vec()),
            secret,
            secret_len,
            veil_dir,
            veil_dir_len,
            instance_label,
            instance_label_len,
            err_out,
        )
    }
}

/// Provision this device under the identity a RECOVERY CERTIFICATE names.
///
/// The half that made a certificate a keepsake rather than a recovery medium.
/// An XVRC is re-wrapped under its own high-entropy code precisely so the
/// exported file is not openable by the words — and every provisioning path
/// opened credentials with the PHRASE, so a device that stored a certificate
/// booted DEGENERATE: no sovereign document, and the identity's address gone
/// while the certificate sat right there. Measured against the real library on
/// 2026-09-12: `ensureSovereignIdentity` returned null for exactly the blob
/// the app writes when someone recovers.
///
/// It works because the certificate carries the WHOLE master. What it does not
/// carry is the BIP-39 seed behind the Ed25519 half — `derive_master_sk_ed25519`
/// is one-way — so this restores the identity exactly, same `node_id`, and
/// cannot write a `master.enc`. [`MasterRecovery`] is where that distinction
/// lives.
///
/// `identity_toml` names the key THIS device signs with, exactly as the
/// phrase-taking sibling uses it: the device key is the host's, the identity is
/// the certificate's.
///
/// `code` is the certificate's own recovery code, SECRET, and wiped in place
/// before return on every path. It is not a phrase and is never decoded as one.
///
/// # Safety
/// `certificate` readable for its length; `code` writable for `code_len` and
/// wiped on every path; `veil_dir`, `instance_label` and `identity_toml`
/// readable for their lengths; `err_out` a writable slot.
#[cfg(feature = "node-embedded")]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_provision_identity_from_certificate_zeroize(
    certificate: *const u8,
    certificate_len: usize,
    code: *mut u8,
    code_len: usize,
    veil_dir: *const u8,
    veil_dir_len: usize,
    instance_label: *const u8,
    instance_label_len: usize,
    identity_toml: *const u8,
    identity_toml_len: usize,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe { clear_err(err_out) };
    // ARMED FIRST: every refusal below used to be a path that left the
    // caller's secret where they put it (report14 V14-M14).
    let Some(_code_guard) = (unsafe { ZeroOnDrop::arm(code, code_len) }) else {
        unsafe { write_err(err_out, "code is NULL or too long (>4 KiB)") };
        return VEIL_ERR_INVALID_ARG;
    };
    if certificate.is_null() || certificate_len == 0 {
        unsafe { write_err(err_out, "certificate is NULL or empty") };
        return VEIL_ERR_INVALID_ARG;
    }
    let Some(dir_str) = (unsafe { slice_to_str(veil_dir, veil_dir_len) }) else {
        unsafe { write_err(err_out, "veil_dir is NULL or invalid UTF-8") };
        return VEIL_ERR_INVALID_ARG;
    };
    let Some(label_str) = (unsafe { slice_to_str(instance_label, instance_label_len) }) else {
        unsafe { write_err(err_out, "instance_label is NULL or invalid UTF-8") };
        return VEIL_ERR_INVALID_ARG;
    };
    let Some(toml_str) = (unsafe { slice_to_str(identity_toml, identity_toml_len) }) else {
        unsafe { write_err(err_out, "identity_toml is NULL or invalid UTF-8") };
        return VEIL_ERR_INVALID_ARG;
    };

    let cert_bytes = unsafe { std::slice::from_raw_parts(certificate, certificate_len) };
    if !cert_bytes.starts_with(b"XVRC") {
        // Named, because the near miss is handing this the sovereign BUNDLE:
        // that one opens with the phrase and has its own entry point.
        unsafe {
            write_err(
                err_out,
                "this is not an XVRC recovery certificate. A sovereign bundle \
                 opens with the phrase — use \
                 veil_provision_hybrid_identity_from_credential_zeroize for it.",
            )
        };
        return VEIL_ERR_INVALID_ARG;
    }
    let code_bytes = unsafe { std::slice::from_raw_parts(code as *const u8, code_len) };
    let material =
        match veil_identity::sovereign_bundle::open_recovery_certificate(cert_bytes, code_bytes) {
            Ok(m) => m,
            Err(e) => {
                unsafe { write_err(err_out, format!("certificate did not open: {e}")) };
                return VEIL_ERR_INVALID_ARG;
            }
        };
    let Some(falcon_bundle) = material.master_falcon_bundle() else {
        unsafe {
            write_err(
                err_out,
                "this certificate is not Ed25519+Falcon-512, so it names no \
                 hybrid master",
            )
        };
        return VEIL_ERR_INVALID_ARG;
    };
    let Some(master_ed_sk) = material.master_ed25519_secret_key() else {
        unsafe { write_err(err_out, "this certificate carries no Ed25519 master half") };
        return VEIL_ERR_INVALID_ARG;
    };

    // The device key is the HOST's, read from the node config it already runs
    // on — the same rule the phrase-taking sibling follows, and the reason two
    // devices of one identity are told apart at all.
    let config = match veil_cfg::parse_toml_str(toml_str) {
        Ok(c) => c,
        Err(e) => {
            unsafe { write_err(err_out, format!("identity_toml parse failed: {e}")) };
            return VEIL_ERR_INVALID_ARG;
        }
    };
    let Some(identity) = config.identity else {
        unsafe { write_err(err_out, "identity_toml has no [identity] section") };
        return VEIL_ERR_INVALID_ARG;
    };
    use base64::{Engine as _, engine::general_purpose::STANDARD};
    let device_seed = match STANDARD.decode(identity.private_key.as_bytes()) {
        Ok(bytes) if bytes.len() == 32 => {
            let mut seed = [0u8; 32];
            seed.copy_from_slice(&bytes);
            zeroize::Zeroizing::new(seed)
        }
        _ => {
            unsafe { write_err(err_out, "identity_toml key is not a 32-byte Ed25519 seed") };
            return VEIL_ERR_INVALID_ARG;
        }
    };

    let now_unix = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    match veil_identity::sovereign_flow::restore_identity(
        veil_identity::sovereign_flow::RestoreIdentityOptions {
            veil_dir: std::path::PathBuf::from(dir_str),
            master: veil_identity::sovereign_flow::MasterRecovery::Ed25519SecretKey(master_ed_sk),
            save_encrypted_with_password: None,
            argon2_params_override: None,
            instance_label: label_str.chars().take(64).collect::<String>(),
            pow_difficulty: 0,
            now_unix,
            valid_until_unix: now_unix + VEIL_DEFAULT_RESTORE_VALIDITY_SECS,
            algo: veil_types::SignatureAlgorithm::Ed25519Falcon512Hybrid,
            master_falcon_keypair_bytes: Some(falcon_bundle.to_vec()),
            device_sk_seed: Some(device_seed),
        },
    ) {
        Ok(_) => VEIL_OK,
        Err(e) => {
            unsafe { write_err(err_out, format!("restore_identity: {e}")) };
            VEIL_ERR
        }
    }
}

#[cfg(feature = "node-embedded")]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_restore_identity_from_phrase_zeroize_with_node_key(
    phrase: *mut u8,
    phrase_len: usize,
    veil_dir: *const u8,
    veil_dir_len: usize,
    instance_label: *const u8,
    instance_label_len: usize,
    identity_toml: *const u8,
    identity_toml_len: usize,
    err_out: *mut *mut c_char,
) -> c_int {
    // ARMED FIRST. Everything below can refuse the call — a NULL TOML, one
    // that will not parse, a key of the wrong algorithm — and every one of
    // those returns used to leave the caller's phrase exactly where it was
    // (report14 V14-M14). The inner call arms its own guard as well; wiping a
    // buffer twice costs nothing.
    let Some(_phrase_guard) = (unsafe { ZeroOnDrop::arm(phrase, phrase_len) }) else {
        unsafe { write_err(err_out, "phrase is NULL or too long (>4 KiB)") };
        return VEIL_ERR_INVALID_ARG;
    };
    let Some(toml_str) = (unsafe { slice_to_str(identity_toml, identity_toml_len) }) else {
        unsafe { write_err(err_out, "identity_toml is NULL or invalid UTF-8") };
        return VEIL_ERR_INVALID_ARG;
    };
    let config = match veil_cfg::parse_toml_str(toml_str) {
        Ok(c) => c,
        Err(e) => {
            unsafe { write_err(err_out, format!("identity_toml parse failed: {e}")) };
            return VEIL_ERR_INVALID_ARG;
        }
    };
    let Some(identity) = config.identity else {
        unsafe { write_err(err_out, "identity_toml carries no [identity]") };
        return VEIL_ERR_INVALID_ARG;
    };
    if identity.algo != veil_types::SignatureAlgorithm::Ed25519 {
        unsafe {
            write_err(
                err_out,
                "only an Ed25519 node key can be named as a device subkey",
            )
        };
        return VEIL_ERR_INVALID_ARG;
    }
    let key_b64 = identity.private_key;
    use base64::{Engine as _, engine::general_purpose::STANDARD};
    // Ed25519 private keys ARE the 32-byte seed. Anything else is not a key
    // this document can name, and guessing would put a subkey in the document
    // that signs nothing.
    let seed = match STANDARD.decode(key_b64.as_bytes()) {
        Ok(bytes) if bytes.len() == 32 => {
            let mut seed = [0u8; 32];
            seed.copy_from_slice(&bytes);
            zeroize::Zeroizing::new(seed)
        }
        _ => {
            unsafe { write_err(err_out, "identity_toml key is not a 32-byte Ed25519 seed") };
            return VEIL_ERR_INVALID_ARG;
        }
    };
    unsafe {
        restore_from_phrase_inner(
            Some(seed),
            None,
            phrase,
            phrase_len,
            veil_dir,
            veil_dir_len,
            instance_label,
            instance_label_len,
            err_out,
        )
    }
}

/// Admit a device to the identity whose `identity_document.bin` is in
/// `veil_dir`, appending its key under the master derived from `phrase` and
/// rewriting the document in place.
///
/// This is what lets one identity hold several devices, and the alternative is
/// not "one document each". `node_id` is BLAKE3(master_pk), so two devices
/// restored from one phrase publish two single-key documents under the SAME id;
/// the later publisher displaces the earlier, and the displaced device stays
/// online believing it is reachable.
///
/// `device_pubkey` may be NULL, and for an embedding application that is the
/// usual call: it means "this device's own key", read from
/// `device_identity_sk.bin` in `veil_dir`, so the caller never handles key
/// material at all. The flow it serves is a merge — a device restored from the
/// phrase receives the other device's document, drops it into `veil_dir`, and
/// calls this to add itself. The previous signer's secret is on the other
/// machine, so the document is re-signed by the newly delegated key and
/// `sig_key_idx` moves to it; every subkey is master-signed, so a verifier
/// accepts either.
///
/// `phrase` is a SECRET, passed as a writable `(*mut u8, len)` buffer that is
/// overwritten with `0` before return on EVERY path. Returns `VEIL_OK` on
/// success; on failure sets `*err_out` and returns `VEIL_ERR`. Refuses, rather
/// than guesses, when the phrase belongs to a different identity than the
/// document does.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_delegate_device_from_phrase_zeroize(
    phrase: *mut u8,
    phrase_len: usize,
    veil_dir: *const u8,
    veil_dir_len: usize,
    device_pubkey: *const u8,
    device_pubkey_len: usize,
    err_out: *mut *mut c_char,
) -> c_int {
    // ONE body. This is [`veil_delegate_device_zeroize`] with no credential,
    // so the phrase path and the credential path cannot drift on what they
    // refuse, what they wipe, or which master they end up using.
    unsafe {
        veil_delegate_device_zeroize(
            std::ptr::null(),
            0,
            phrase,
            phrase_len,
            veil_dir,
            veil_dir_len,
            device_pubkey,
            device_pubkey_len,
            err_out,
        )
    }
}

/// Move a device's delegation window forward, re-signed by the master.
///
/// What a device needs when it comes back from a week offline, and it is not
/// a re-enrolment: the device keeps its key, its `device_id` and its address,
/// and only the window and the master's certificate over it move. Nothing
/// else on the device changes, and no other device has to be present.
///
/// Which master signs follows the same rule the boot uses to decide which
/// identity a phrase names: a `credential` means the hybrid master, and it is
/// opened here with `secret`; without one the master is the Ed25519 key
/// `secret` derives as a phrase. Passing a credential that does not belong to
/// this document is refused rather than guessed.
///
/// `device_pubkey` may be NULL, and for an application that is the usual call:
/// it means this device's own key, read from `device_identity_sk.bin`, so the
/// caller never handles key material.
///
/// Refuses a device the document does not name (renewal never admits one), a
/// revoked device, and a window that does not move forward.
///
/// # Safety
/// `credential` readable for `credential_len` or NULL; `secret` writable for
/// `secret_len` and wiped on every path; `veil_dir` readable for its length;
/// `device_pubkey` readable for its length or NULL; `err_out` a writable slot.
#[cfg(feature = "node-embedded")]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_reissue_device_delegation_zeroize(
    credential: *const u8,
    credential_len: usize,
    secret: *mut u8,
    secret_len: usize,
    veil_dir: *const u8,
    veil_dir_len: usize,
    device_pubkey: *const u8,
    device_pubkey_len: usize,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe { clear_err(err_out) };
    let Some(_secret_guard) = (unsafe { ZeroOnDrop::arm(secret, secret_len) }) else {
        unsafe { write_err(err_out, "secret is NULL or too long (>4 KiB)") };
        return VEIL_ERR_INVALID_ARG;
    };
    let Some(dir_str) = (unsafe { slice_to_str(veil_dir, veil_dir_len) }) else {
        unsafe { write_err(err_out, "veil_dir is NULL or invalid UTF-8") };
        return VEIL_ERR_INVALID_ARG;
    };
    let dir = std::path::PathBuf::from(dir_str);
    let secret_bytes = unsafe { std::slice::from_raw_parts(secret as *const u8, secret_len) };

    let master = if credential.is_null() || credential_len == 0 {
        // No credential: the classic identity, whose master the words give.
        let Ok(phrase_str) = std::str::from_utf8(secret_bytes) else {
            unsafe { write_err(err_out, "secret is not valid UTF-8") };
            return VEIL_ERR_INVALID_ARG;
        };
        match veil_identity::master_seed::decode_master_seed_from_phrase(phrase_str) {
            Ok(seed) => veil_identity::sovereign_flow::MasterSecret::Seed(seed),
            Err(e) => {
                unsafe { write_err(err_out, format!("decode phrase: {e}")) };
                return VEIL_ERR;
            }
        }
    } else {
        let credential_bytes = unsafe { std::slice::from_raw_parts(credential, credential_len) };
        let opened = if credential_bytes.starts_with(b"XVRC") {
            veil_identity::sovereign_bundle::open_recovery_certificate(
                credential_bytes,
                secret_bytes,
            )
        } else {
            veil_identity::sovereign_bundle::open(credential_bytes, secret_bytes)
        };
        match opened {
            Ok(material) => match material.as_master_secret() {
                Some(m) => m,
                None => {
                    unsafe {
                        write_err(
                            err_out,
                            "this credential is not Ed25519+Falcon-512, so it names no \
                             hybrid master",
                        )
                    };
                    return VEIL_ERR_INVALID_ARG;
                }
            },
            Err(e) => {
                unsafe { write_err(err_out, format!("credential did not open: {e}")) };
                return VEIL_ERR_INVALID_ARG;
            }
        }
    };

    let device = if device_pubkey.is_null() || device_pubkey_len == 0 {
        None
    } else {
        Some(unsafe { std::slice::from_raw_parts(device_pubkey, device_pubkey_len) }.to_vec())
    };

    let now_unix = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    match veil_identity::sovereign_flow::reissue_device_delegation(
        veil_identity::sovereign_flow::ReissueDelegationOptions {
            veil_dir: dir,
            master,
            device_pubkey: device,
            now_unix,
            valid_until_unix: now_unix + VEIL_DEFAULT_RESTORE_VALIDITY_SECS,
            out_path: None,
        },
    ) {
        Ok(_) => VEIL_OK,
        Err(e) => {
            unsafe { write_err(err_out, format!("reissue_device_delegation: {e}")) };
            VEIL_ERR
        }
    }
}

/// The master a device-lifecycle call signs with.
///
/// Chosen the way the boot chooses which identity a secret names: a
/// `credential` means the HYBRID master, opened with `secret`; none means the
/// Ed25519 master `secret` gives as a BIP-39 phrase.
///
/// In ONE place on purpose. The three entry points that amend a document under
/// the master used to choose separately, and the two that ADD and REMOVE a
/// device chose "the phrase, always". A hybrid master is 929 bytes of
/// Ed25519+Falcon-512 and the identity's address is BLAKE3 over all of them,
/// so those two refused every hybrid identity with `UnsupportedMasterAlgo`: an
/// app that creates hybrid identities — xVeil does, by default — could never
/// link a second device to one, nor revoke a stolen one. The flows underneath
/// had been algorithm-generic for a while; only the choice of master here was
/// not, and nothing noticed because the two stands it takes to see it are two
/// devices.
///
/// # Safety
/// `credential` readable for `credential_len` or NULL; `err_out` a writable
/// slot.
unsafe fn master_secret_for_device_lifecycle(
    credential: *const u8,
    credential_len: usize,
    secret_bytes: &[u8],
    err_out: *mut *mut c_char,
) -> Result<veil_identity::sovereign_flow::MasterSecret, c_int> {
    if credential.is_null() || credential_len == 0 {
        // No credential: the classic identity, whose master the words give.
        let Ok(phrase_str) = std::str::from_utf8(secret_bytes) else {
            unsafe { write_err(err_out, "secret is not valid UTF-8") };
            return Err(VEIL_ERR_INVALID_ARG);
        };
        return match veil_identity::master_seed::decode_master_seed_from_phrase(phrase_str) {
            Ok(seed) => Ok(veil_identity::sovereign_flow::MasterSecret::Seed(seed)),
            Err(e) => {
                unsafe { write_err(err_out, format!("decode phrase: {e}")) };
                Err(VEIL_ERR)
            }
        };
    }
    let credential_bytes = unsafe { std::slice::from_raw_parts(credential, credential_len) };
    let opened = if credential_bytes.starts_with(b"XVRC") {
        veil_identity::sovereign_bundle::open_recovery_certificate(credential_bytes, secret_bytes)
    } else {
        veil_identity::sovereign_bundle::open(credential_bytes, secret_bytes)
    };
    match opened {
        Ok(material) => match material.as_master_secret() {
            Some(m) => Ok(m),
            None => {
                unsafe {
                    write_err(
                        err_out,
                        "this credential is not Ed25519+Falcon-512, so it names no \
                         hybrid master",
                    )
                };
                Err(VEIL_ERR_INVALID_ARG)
            }
        },
        Err(e) => {
            unsafe { write_err(err_out, format!("credential did not open: {e}")) };
            Err(VEIL_ERR_INVALID_ARG)
        }
    }
}

/// Admit a device into this identity's document under the master — hybrid or
/// classic.
///
/// The call an application should make. Everything
/// `veil_delegate_device_from_phrase_zeroize` documents holds here; the one
/// difference is WHICH master signs the new subkey's certificate, and it
/// follows the credential exactly as renewal and the boot decide it. The
/// phrase-only sibling stays for a classic identity and forwards here with no
/// credential, so the two can no longer disagree.
///
/// `credential` may be NULL (a classic identity, `secret` is the phrase) or a
/// sovereign bundle / `XVRC` recovery certificate, which `secret` opens.
///
/// `device_pubkey` may be NULL, and for an embedding application that is the
/// usual call: it means "this device's own key", read from
/// `device_identity_sk.bin` in `veil_dir`.
///
/// `secret` is SECRET — a writable `(*mut u8, len)` buffer, overwritten with
/// `0` before return on EVERY path.
///
/// # Safety
/// `credential` readable for `credential_len` or NULL; `secret` writable for
/// `secret_len` and wiped on every path; `veil_dir` readable for its length;
/// `device_pubkey` readable for its length or NULL; `err_out` a writable slot.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_delegate_device_zeroize(
    credential: *const u8,
    credential_len: usize,
    secret: *mut u8,
    secret_len: usize,
    veil_dir: *const u8,
    veil_dir_len: usize,
    device_pubkey: *const u8,
    device_pubkey_len: usize,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe {
        clear_err(err_out);
    }
    let Some(_guard) = (unsafe { ZeroOnDrop::arm(secret, secret_len) }) else {
        unsafe { write_err(err_out, "secret is NULL or too long (>4 KiB)") };
        return VEIL_ERR_INVALID_ARG;
    };
    let Some(dir_str) = (unsafe { slice_to_str(veil_dir, veil_dir_len) }) else {
        unsafe {
            write_err(err_out, "veil_dir is NULL or invalid UTF-8");
        }
        return VEIL_ERR_INVALID_ARG;
    };
    let dir = std::path::PathBuf::from(dir_str);
    let secret_bytes = unsafe { std::slice::from_raw_parts(secret as *const u8, secret_len) };

    // NULL means "my own key". Resolved here rather than left to the caller so
    // an application never has to load, carry or pass a signing key.
    let pubkey: Vec<u8> = if device_pubkey.is_null() {
        match veil_identity::sovereign_flow::load_identity_sk(&dir) {
            Ok(seed) => ed25519_dalek::SigningKey::from_bytes(seed.as_array())
                .verifying_key()
                .as_bytes()
                .to_vec(),
            Err(e) => {
                unsafe {
                    write_err(err_out, format!("load own device key: {e}"));
                }
                return VEIL_ERR;
            }
        }
    } else {
        unsafe { std::slice::from_raw_parts(device_pubkey, device_pubkey_len) }.to_vec()
    };

    let master = match unsafe {
        master_secret_for_device_lifecycle(credential, credential_len, secret_bytes, err_out)
    } {
        Ok(m) => m,
        Err(code) => return code,
    };

    let now_unix = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    match veil_identity::sovereign_flow::delegate_device(
        veil_identity::sovereign_flow::DelegateDeviceOptions {
            veil_dir: dir,
            master,
            device_pubkey: pubkey,
            now_unix,
            valid_until_unix: now_unix + VEIL_DEFAULT_RESTORE_VALIDITY_SECS,
            out_path: None,
        },
    ) {
        Ok(_output) => VEIL_OK,
        Err(e) => {
            unsafe {
                write_err(err_out, format!("delegate_device: {e}"));
            }
            VEIL_ERR
        }
    }
}

/// When THIS device's delegation runs out, in Unix seconds.
///
/// The one question a host needs to answer both of its own: whether to renew
/// now, and whether to warn. Asked here rather than parsed in the host because
/// the document's layout is veil's, and a second reader of a wire format is a
/// second thing to keep in step — the drift would be silent and the symptom
/// would be a device that went quiet.
///
/// Writes `0` when this device is not named by the document at all, which is
/// not an error: a node with no sovereign identity has no delegation to
/// expire.
///
/// # Safety
/// `veil_dir` readable for its length; `out_valid_until_unix` a writable
/// `u64` slot; `err_out` a writable slot.
#[cfg(feature = "node-embedded")]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn veil_device_delegation_valid_until(
    veil_dir: *const u8,
    veil_dir_len: usize,
    out_valid_until_unix: *mut u64,
    err_out: *mut *mut c_char,
) -> c_int {
    unsafe { clear_err(err_out) };
    if out_valid_until_unix.is_null() {
        unsafe { write_err(err_out, "out_valid_until_unix is NULL") };
        return VEIL_ERR_INVALID_ARG;
    }
    let Some(dir_str) = (unsafe { slice_to_str(veil_dir, veil_dir_len) }) else {
        unsafe { write_err(err_out, "veil_dir is NULL or invalid UTF-8") };
        return VEIL_ERR_INVALID_ARG;
    };
    let dir = std::path::PathBuf::from(dir_str);
    let doc_bytes = match std::fs::read(dir.join("identity_document.bin")) {
        Ok(b) => b,
        Err(e) => {
            unsafe { write_err(err_out, format!("read identity_document.bin: {e}")) };
            return VEIL_ERR;
        }
    };
    let doc = match veil_proto::identity_document::IdentityDocument::decode(&doc_bytes) {
        Ok(d) => d,
        Err(e) => {
            unsafe { write_err(err_out, format!("document decode: {e}")) };
            return VEIL_ERR;
        }
    };
    // This device's own key, not the document's active one: on a device that
    // is not the signer those differ, and the window that matters here is the
    // one that decides whether THIS device is still admitted.
    let own = match veil_identity::sovereign_flow::load_identity_sk(&dir) {
        Ok(seed) => ed25519_dalek::SigningKey::from_bytes(seed.as_array())
            .verifying_key()
            .to_bytes()
            .to_vec(),
        Err(e) => {
            unsafe { write_err(err_out, format!("load own device key: {e}")) };
            return VEIL_ERR;
        }
    };
    let valid_until = doc
        .identity_keys
        .iter()
        .find(|k| k.pubkey == own)
        .map(|k| k.valid_until_unix)
        .unwrap_or(0);
    unsafe { *out_valid_until_unix = valid_until };
    VEIL_OK
}

