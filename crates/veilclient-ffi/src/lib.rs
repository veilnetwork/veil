/// This build's ABI contract hash: the SHA-256 of the generated
/// `veil_ffi.h`, as a static NUL-terminated lowercase hex string.
///
/// **Call this before anything else, and refuse to load the library when it
/// does not match the value your bindings were generated from.**
///
/// A missing symbol is a loud, safe failure — the loader reports it and
/// nothing runs. The dangerous case is a symbol that is still THERE and no
