/// Emit an FFI-side diagnostic without panicking if stderr is closed/broken.
pub(crate) fn ffi_diag(msg: &str) {
    #[cfg(target_os = "android")]
    log::warn!("{msg}");
    #[cfg(not(target_os = "android"))]
    {
        use std::io::Write as _;
        let _ = writeln!(std::io::stderr(), "{msg}");
    }
}

